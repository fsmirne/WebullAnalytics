"""Rebuilds ThetaData's gRPC .proto files from the descriptors embedded in the installed `thetadata` Python library.

ThetaData publishes no .proto spec; the library ships only generated *_pb2.py modules whose serialized FileDescriptorProtos are the
protocol. Their support confirmed (2026-10-20) that a custom C# client may call these endpoints, unsupported, tracking whatever the
current library does — so when the library updates, upgrade it and re-run this to regenerate the C# client's protos:

    python -m pip install --upgrade thetadata
    python scripts/thetadata_proto_extract.py

Writes Api/ThetaData/Protos/{endpoints,v3grpc/endpoints}.proto with a csharp_namespace option added (nothing else changes on the
wire) and the library version stamped in the header; ThetaDataClient.LibraryVersion must be bumped to match.
"""
import subprocess
import sys
from importlib.metadata import version
from pathlib import Path

from google.protobuf import descriptor_pb2 as dp
from thetadata._proto import endpoints_pb2 as base_pb2
from thetadata._proto.v3grpc import endpoints_pb2 as v3_pb2

OUT_DIR = Path(__file__).resolve().parent.parent / "Api" / "ThetaData" / "Protos"
CSHARP_NAMESPACES = {"endpoints.proto": "WebullAnalytics.Api.ThetaData.Proto", "v3grpc/endpoints.proto": "WebullAnalytics.Api.ThetaData.Proto.V3"}

SCALARS = {
	dp.FieldDescriptorProto.TYPE_DOUBLE: "double", dp.FieldDescriptorProto.TYPE_FLOAT: "float", dp.FieldDescriptorProto.TYPE_INT64: "int64",
	dp.FieldDescriptorProto.TYPE_UINT64: "uint64", dp.FieldDescriptorProto.TYPE_INT32: "int32", dp.FieldDescriptorProto.TYPE_FIXED64: "fixed64",
	dp.FieldDescriptorProto.TYPE_FIXED32: "fixed32", dp.FieldDescriptorProto.TYPE_BOOL: "bool", dp.FieldDescriptorProto.TYPE_STRING: "string",
	dp.FieldDescriptorProto.TYPE_BYTES: "bytes", dp.FieldDescriptorProto.TYPE_UINT32: "uint32", dp.FieldDescriptorProto.TYPE_SFIXED32: "sfixed32",
	dp.FieldDescriptorProto.TYPE_SFIXED64: "sfixed64", dp.FieldDescriptorProto.TYPE_SINT32: "sint32", dp.FieldDescriptorProto.TYPE_SINT64: "sint64",
}


def type_name(field: dp.FieldDescriptorProto) -> str:
	return SCALARS.get(field.type) or field.type_name


def map_entries(msg: dp.DescriptorProto) -> dict:
	"""Fully-qualified-suffix name -> (key type, value type) for the message's synthetic map-entry nested types."""
	return {nested.name: (type_name(nested.field[0]), type_name(nested.field[1])) for nested in msg.nested_type if nested.options.map_entry}


def render_field(field: dp.FieldDescriptorProto, maps: dict, indent: str) -> str:
	entry = field.type_name.rsplit(".", 1)[-1] if field.type == dp.FieldDescriptorProto.TYPE_MESSAGE else None
	if field.label == dp.FieldDescriptorProto.LABEL_REPEATED and entry in maps:
		key, value = maps[entry]
		return f"{indent}map<{key}, {value}> {field.name} = {field.number};"
	label = "repeated " if field.label == dp.FieldDescriptorProto.LABEL_REPEATED else "optional " if field.proto3_optional else ""
	return f"{indent}{label}{type_name(field)} {field.name} = {field.number};"


def render_enum(enum: dp.EnumDescriptorProto, indent: str) -> list:
	return [f"{indent}enum {enum.name} {{", *[f"{indent}\t{v.name} = {v.number};" for v in enum.value], f"{indent}}}"]


def render_message(msg: dp.DescriptorProto, indent: str) -> list:
	maps = map_entries(msg)
	lines = [f"{indent}message {msg.name} {{"]
	for enum in msg.enum_type:
		lines += render_enum(enum, indent + "\t")
	for nested in msg.nested_type:
		if not nested.options.map_entry:
			lines += render_message(nested, indent + "\t")
	emitted_oneofs = set()
	for field in msg.field:
		in_real_oneof = field.HasField("oneof_index") and not field.proto3_optional
		if not in_real_oneof:
			lines.append(render_field(field, maps, indent + "\t"))
			continue
		if field.oneof_index in emitted_oneofs:
			continue
		emitted_oneofs.add(field.oneof_index)
		lines.append(f"{indent}\toneof {msg.oneof_decl[field.oneof_index].name} {{")
		lines += [render_field(f, maps, indent + "\t\t") for f in msg.field if f.HasField("oneof_index") and not f.proto3_optional and f.oneof_index == field.oneof_index]
		lines.append(f"{indent}\t}}")
	lines.append(f"{indent}}}")
	return lines


def render_file(module, lib_version: str) -> str:
	fd = dp.FileDescriptorProto()
	module.DESCRIPTOR.CopyToProto(fd)
	if fd.syntax != "proto3":
		sys.exit(f"{fd.name}: expected proto3, got '{fd.syntax}' — the renderer only handles proto3")
	lines = [f"// GENERATED by scripts/thetadata_proto_extract.py from thetadata {lib_version} ({fd.name}). Do not edit; re-run the script.", 'syntax = "proto3";', f"package {fd.package};", ""]
	# Only imports something references: v3grpc declares struct.proto without using it, which protoc warns about on every build.
	body = str(fd.message_type) + str(fd.service)
	lines += [f'import "{dep.name}";' for dep in module.DESCRIPTOR.dependencies if f'".{dep.package}.' in body]
	lines += ["", f'option java_package = "{fd.options.java_package}";', f"option java_multiple_files = {str(fd.options.java_multiple_files).lower()};", f'option csharp_namespace = "{CSHARP_NAMESPACES[fd.name]}";', ""]
	for enum in fd.enum_type:
		lines += render_enum(enum, "") + [""]
	for msg in fd.message_type:
		lines += render_message(msg, "") + [""]
	for service in fd.service:
		lines.append(f"service {service.name} {{")
		for m in service.method:
			lines.append(f"\trpc {m.name}({'stream ' if m.client_streaming else ''}{m.input_type}) returns ({'stream ' if m.server_streaming else ''}{m.output_type});")
		lines += ["}", ""]
	return "\n".join(lines)


def find_protoc() -> tuple:
	"""protoc + its well-known-types include dir from the Grpc.Tools NuGet package the C# build already restores (newest version)."""
	tools = sorted((Path.home() / ".nuget" / "packages" / "grpc.tools").glob("*"), key=lambda p: [int(x) for x in p.name.split(".") if x.isdigit()])
	if not tools:
		sys.exit("Grpc.Tools not in the NuGet cache — build WebullAnalytics.csproj once (it restores Grpc.Tools), then re-run")
	exe = "windows_x64/protoc.exe" if sys.platform == "win32" else "linux_x64/protoc"
	return tools[-1] / "tools" / exe, tools[-1] / "build" / "native" / "include"


def comparable(fd: dp.FileDescriptorProto) -> dp.FileDescriptorProto:
	"""The wire-relevant part of a file descriptor: types, fields, numbers, services. Options (we add csharp_namespace), imports (we drop
	unused ones) and protoc's derived json_name are not on the wire."""
	out = dp.FileDescriptorProto(package=fd.package, enum_type=fd.enum_type, message_type=fd.message_type, service=fd.service)
	stack = list(out.message_type)
	while stack:
		msg = stack.pop()
		for field in msg.field:
			field.ClearField("json_name")
		stack.extend(msg.nested_type)
	return out


def verify(modules):
	"""Compiles the written .proto files with protoc and asserts each is wire-identical to the library descriptor it was rendered from."""
	protoc, include = find_protoc()
	descriptor_set = OUT_DIR / "descriptor_set.tmp"
	try:
		subprocess.run([str(protoc), f"-I{OUT_DIR}", f"-I{include}", f"--descriptor_set_out={descriptor_set}", *[m.DESCRIPTOR.name for m in modules]], check=True, cwd=OUT_DIR)
		compiled = {fd.name: fd for fd in dp.FileDescriptorSet.FromString(descriptor_set.read_bytes()).file}
	finally:
		descriptor_set.unlink(missing_ok=True)
	for module in modules:
		original = dp.FileDescriptorProto()
		module.DESCRIPTOR.CopyToProto(original)
		if comparable(original) != comparable(compiled[module.DESCRIPTOR.name]):
			sys.exit(f"{module.DESCRIPTOR.name}: rendered .proto does NOT round-trip to the library descriptor — the renderer missed a construct this library version uses")
		print(f"verified {module.DESCRIPTOR.name}: wire-identical to thetadata's descriptor")


def main():
	lib_version = version("thetadata")
	modules = (base_pb2, v3_pb2)
	for module in modules:
		path = OUT_DIR / module.DESCRIPTOR.name
		path.parent.mkdir(parents=True, exist_ok=True)
		path.write_text(render_file(module, lib_version), encoding="utf-8", newline="\n")
		print(f"wrote {path}")
	verify(modules)


if __name__ == "__main__":
	main()
